CREATE DATABASE IF NOT EXISTS employeesDB;
use employeesDB;

SET FOREIGN_KEY_CHECKS=0;
DROP TABLE IF EXISTS EMPLOYEES;
DROP TABLE IF EXISTS JOBS;
DROP TABLE IF EXISTS departments;
DROP TABLE IF EXISTS REGIONS;
DROP TABLE IF EXISTS COUNTRIES;
DROP TABLE IF EXISTS LOCATIONS;
DROP TABLE IF EXISTS JOB_HISTORY;


CREATE TABLE  REGIONS
   (	REGION_ID DECIMAL(2) NOT NULL ,
	REGION_NAME VARCHAR(50),
	 CONSTRAINT `REG_ID_PK` PRIMARY KEY (REGION_ID)
   )
;
CREATE TABLE  COUNTRIES
   (	COUNTRY_ID CHAR(4)  NOT NULL ,
	COUNTRY_NAME VARCHAR(50),
	REGION_ID DECIMAL(2),
	 CONSTRAINT COUNTRY_C_ID_PK PRIMARY KEY (COUNTRY_ID),
	 CONSTRAINT `COUNTRY_REGION_FK` FOREIGN KEY (REGION_ID) REFERENCES REGIONS (REGION_ID)
   );
CREATE TABLE  LOCATIONS
   (	LOCATION_ID DECIMAL(4,0),
	STREET_ADDRESS VARCHAR(60),
	POSTAL_CODE VARCHAR(12),
	CITY VARCHAR(50) NOT NULL ,
	STATE_PROVINCE VARCHAR(50),
	COUNTRY_ID CHAR(4),
	 CONSTRAINT LOC_ID_PK PRIMARY KEY (LOCATION_ID),
	 CONSTRAINT `LOC_COUNTRY_FK` FOREIGN KEY (COUNTRY_ID) REFERENCES COUNTRIES (COUNTRY_ID)
   );

CREATE TABLE  JOBS
   (	JOB_ID VARCHAR(10),
	JOB_TITLE VARCHAR(35) NOT NULL,
	MIN_SALARY DECIMAL(6,0),
	MAX_SALARY DECIMAL(6,0),
	CONSTRAINT JOB_ID_PK PRIMARY KEY (JOB_ID)
);
CREATE TABLE  EMPLOYEES
   (	EMPLOYEE_ID DECIMAL(6,0),
	FIRST_NAME VARCHAR(20),
	LAST_NAME VARCHAR(25)  NOT NULL ,
	EMAIL VARCHAR(51)  NOT NULL ,
	PHONE_NUMBER VARCHAR(20),
	HIRE_DATE DATE NOT NULL ,
	JOB_ID VARCHAR(10) NOT NULL ,
	SALARY DECIMAL(8,2),
	COMMISSION_PCT DECIMAL(2,2),
	MANAGER_ID DECIMAL(6,0),
	DEPARTMENT_ID DECIMAL(4,0),
	CHECK (salary > 0) ,
	CONSTRAINT EMP_ID_PK PRIMARY KEY (EMPLOYEE_ID) ,
	CONSTRAINT EMP_EMAIL_UK UNIQUE (EMAIL),
	CONSTRAINT `EMP_JOB_FK` foreign key (JOB_ID) REFERENCES JOBS(JOB_ID)
);
CREATE TABLE  DEPARTMENTS
	(	DEPARTMENT_ID DECIMAL(4,0),
	DEPARTMENT_NAME VARCHAR(30) NOT NULL,
	MANAGER_ID DECIMAL(6,0),
	LOCATION_ID DECIMAL(4,0),
	CONSTRAINT DEPT_ID_PK PRIMARY KEY (DEPARTMENT_ID),
	CONSTRAINT `DEP_LOCATION_FK` FOREIGN KEY (LOCATION_ID) REFERENCES  LOCATIONS (LOCATION_ID),
	CONSTRAINT `DEP_MANAGER_FK` FOREIGN KEY (MANAGER_ID) REFERENCES  EMPLOYEES (EMPLOYEE_ID)
);
ALTER TABLE EMPLOYEES ADD constraint `EMP_BOSS_FK` FOREIGN KEY (MANAGER_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID);
ALTER TABLE EMPLOYEES ADD constraint `EMP_DEPARTMENT_FK` FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENTS(DEPARTMENT_ID);


CREATE TABLE  JOB_HISTORY
   (	EMPLOYEE_ID DECIMAL(6,0) NOT NULL ,
	START_DATE DATE NOT NULL ,
	END_DATE DATE  NOT NULL ,
	JOB_ID VARCHAR(10) NOT NULL ,
	DEPARTMENT_ID DECIMAL(4,0),
	CONSTRAINT JHIST_DATE_INTERVAL CHECK (end_date > start_date) ,
	CONSTRAINT JHIST_EMP_ID_ST_DATE_PK PRIMARY KEY (EMPLOYEE_ID, START_DATE),
	CONSTRAINT JHIST_EMPLOYEE_FK FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES (EMPLOYEE_ID) ,
	CONSTRAINT `JHIST_DEP_FK` FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENTS (DEPARTMENT_ID),
	CONSTRAINT `JHIST_JOB_FK` FOREIGN KEY (JOB_ID) REFERENCES JOBS (JOB_ID)
   );

